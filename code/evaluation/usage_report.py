"""Generate ``usage_report.md`` from the logged model calls (never hand-typed).

The LLM and vision clients append one JSON line per real model call to
``.cache/usage_llm.jsonl`` / ``.cache/usage_vision.jsonl``; ``code/main.py``
appends one line per pipeline run to ``.cache/run_log.jsonl`` recording which
slice of each usage log that run added and the SHA-256 of the ``output.csv`` it
wrote. This script reports:

* the **producing run** — the run that made the model calls behind the current
  ``output.csv`` (the earliest run with that output digest that made calls), and
* any **reproduction runs** — later runs with the same digest (warm cache,
  expected to make zero calls).

Usage::

    python code/evaluation/usage_report.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
_CACHE = _REPO_ROOT / ".cache"
_LOGS = {"llm": _CACHE / "usage_llm.jsonl", "vision": _CACHE / "usage_vision.jsonl"}
_RUN_LOG = _CACHE / "run_log.jsonl"
_OUT = Path(__file__).resolve().parent / "usage_report.md"

_PURPOSE = {"llm": "deletion-intent classification", "vision": "PDF / screenshot extraction"}


def _read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def _usd(x: float, places: int = 4) -> str:
    return f"${x:,.{places}f}"


def build_report() -> str:
    output = _REPO_ROOT / "output.csv"
    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    runs = [r for r in _read_jsonl(_RUN_LOG) if r.get("output_sha256") == digest]
    if not runs:
        raise SystemExit("no run in .cache/run_log.jsonl produced the current output.csv")

    def calls_in(run):
        return sum(e - b for b, e in run["usage_slices"].values())

    # The model calls behind output.csv are those of the most recent run that
    # made calls (it filled the cache from empty); every later run reused that
    # cache. The current output must come from that run or a later one.
    all_runs = _read_jsonl(_RUN_LOG)
    with_calls = [i for i, r in enumerate(all_runs) if calls_in(r) > 0]
    first_current = next(i for i, r in enumerate(all_runs) if r.get("output_sha256") == digest)
    if not with_calls or with_calls[-1] > max(
            i for i, r in enumerate(all_runs) if r.get("output_sha256") == digest):
        raise SystemExit("current output.csv was not produced from the latest model calls")
    producing = all_runs[with_calls[-1]]
    later = all_runs[with_calls[-1] + 1:]
    repro = [r for r in later if r.get("output_sha256") == digest]
    del first_current
    logs = {name: _read_jsonl(path) for name, path in _LOGS.items()}
    requests = producing["requests"]

    rows = []  # (source, provider, model, calls, in, out, cost, errors)
    for source, (start, end) in producing["usage_slices"].items():
        per_model = defaultdict(lambda: [0, 0, 0, 0.0, 0])
        for entry in logs[source][start:end]:
            m = per_model[(entry.get("backend", "openai") or "openai", entry["model"])]
            m[0] += 1
            m[1] += entry.get("prompt_tokens", 0)
            m[2] += entry.get("completion_tokens", 0)
            m[3] += entry.get("estimated_cost_usd", 0.0)
            m[4] += 1 if entry.get("error") else 0
        for (backend, model), (n, tin, tout, cost, errs) in sorted(per_model.items()):
            provider = "OpenAI" if backend in ("openai", "") else f"local ({backend})"
            rows.append((source, provider, model, n, tin, tout, cost, errs))

    tot_calls = sum(r[3] for r in rows)
    tot_in = sum(r[4] for r in rows)
    tot_out = sum(r[5] for r in rows)
    tot_cost = sum(r[6] for r in rows)

    L: list[str] = []
    L.append("# GhostAudit — Model Usage Report")
    L.append("")
    L.append("Generated by `code/evaluation/usage_report.py` from the per-call usage logs "
             "(`.cache/usage_llm.jsonl`, `.cache/usage_vision.jsonl`) and the run ledger "
             "(`.cache/run_log.jsonl`). Nothing here is hand-typed.")
    L.append("")
    L.append("## Final full-dataset run")
    L.append("")
    L.append(f"- Model calls: run `{producing['started']}` → `{producing['finished']}` over "
             f"{requests} requests (`dataset/deletion_requests.csv`), started from an "
             "empty cache, so every model call behind `output.csv` is counted here.")
    final = repro[-1] if repro else producing
    L.append(f"- Final `output.csv` (sha256 `{digest[:16]}…`) was written at "
             f"`{final['finished']}` from that cache; contract-valid: "
             f"{'yes' if final['valid'] else 'no'}.")
    L.append("- Cost is estimated from list prices per 1M tokens "
             "(gpt-4o-mini $0.15 in / $0.60 out; gpt-4o $2.50 in / $10.00 out).")
    L.append("")
    L.append("| Use | Provider | Model | Calls | Input tokens | Output tokens | Total tokens "
             "| Avg tokens / request | Est. cost | Est. cost / request |")
    L.append("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for source, provider, model, n, tin, tout, cost, errs in rows:
        L.append(f"| {_PURPOSE[source]} | {provider} | `{model}` | {n}"
                 f"{f' ({errs} failed)' if errs else ''} | {tin:,} | {tout:,} | "
                 f"{tin + tout:,} | {(tin + tout) / requests:,.1f} | {_usd(cost)} | "
                 f"{_usd(cost / requests, 6)} |")
    L.append(f"| **Overall** | | | **{tot_calls}** | **{tot_in:,}** | **{tot_out:,}** | "
             f"**{tot_in + tot_out:,}** | **{(tot_in + tot_out) / requests:,.1f}** | "
             f"**{_usd(tot_cost)}** | **{_usd(tot_cost / requests, 6)}** |")
    L.append("")
    L.append("Per-request figures divide by all requests in the run. Calls are fewer than "
             "requests because results are cached by content: intent by the exact request "
             "text (identical texts share one call), vision once per evidence file (shared "
             "by every case that cites it).")
    L.append("")
    L.append("## Reproducibility (warm cache)")
    L.append("")
    if later:
        L.append("Runs after the cache was filled (all reuse it):")
        L.append("")
        L.append("| Run started | Model calls | output.csv sha256 |")
        L.append("| --- | ---: | --- |")
        for r in later:
            mark = " (final)" if r.get("output_sha256") == digest else ""
            L.append(f"| `{r['started']}` | {calls_in(r)} | `{r['output_sha256'][:12]}`{mark} |")
        if any(r.get("output_sha256") != digest for r in later):
            L.append("")
            L.append("A run with a different digest made zero calls, so it read the same "
                     "cached model outputs: its difference comes from a code change between "
                     "runs, not from the models.")
        if len(repro) > 1:
            L.append("")
            L.append(f"The final output was reproduced {len(repro)} times with identical "
                     "bytes and zero calls.")
    else:
        L.append("No warm-cache rerun has been recorded yet.")
    L.append("")
    L.append("Every model result is cached on disk (intent keyed by model + prompt + text; "
             "vision by file content hash + prompt version), temperature is 0, and all "
             "decisions downstream of the model outputs are deterministic, so a rerun "
             "makes zero calls and reproduces `output.csv` byte for byte.")
    L.append("")
    L.append("## Where models are used")
    L.append("")
    L.append("- **Intent** (`gpt-4o-mini`): does the request text authorize deletion? "
             "Falls back to a deterministic multilingual regex without a key.")
    L.append("- **Vision** (`gpt-4o`): read the records shown in PDFs and screenshots "
             "(resource id or printed reference, identifiers, explicit state). Results "
             "are plausibility-checked (and, for PDFs, must appear verbatim in the text).")
    L.append("- Everything else — identity resolution, discovery, policy, status, "
             "remediation ordering — is deterministic code; no model decides a status.")
    L.append("")
    return "\n".join(L)


def main() -> int:
    _OUT.write_text(build_report(), encoding="utf-8")
    print(f"[written to {_OUT}]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
